#include <unistd.h>

int	ft_is_prime(int nb)
{
	int	i;

	if (nb <= 1)
		return (0);
	i = 2;
	while (i != nb)
	{
		if ((nb % i == 0) && (i != nb || i != 1))
			return (0);
		i++;
	}
	return (1);
}
